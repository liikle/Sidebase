export function formatCost({ min, max }: { min: number; max: number }): string {
  const f = (n: number) => (n >= 1000 ? `$${(n / 1000).toFixed(n % 1000 === 0 ? 0 : 1)}k` : `$${n}`)
  if (max === 0) return '$0'
  if (min === max) return f(min)
  return `${f(min)}–${f(max)}`
}

export function formatHours({ min, max }: { min: number; max: number }): string {
  return `${min}–${max} hrs/wk`
}
